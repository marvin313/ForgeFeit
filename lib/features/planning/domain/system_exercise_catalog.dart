  static final List<ExerciseSelection> all = List.unmodifiable(
    _seeds.map((seed) => seed.build()),
  );

  static final Map<String, ExerciseSelection> _byKey = Map.unmodifiable({
    for (final exercise in all) exercise.exerciseId: exercise,
  });

  static ExerciseSelection? byKey(String key) => _byKey[key];

  static List<ExerciseSelection> search({
    String query = '',
    MuscleGroup? muscleGroup,
    ExerciseEquipment? equipment,
  }) {
    final seen = <String>{};
    return List.unmodifiable(
      all.where(
        (exercise) =>
            seen.add(exercise.exerciseId) &&
            exercise.matchesSearch(query) &&
            (muscleGroup == null ||
                exercise.primaryMuscleGroup == muscleGroup ||
                exercise.secondaryMuscleGroups.contains(muscleGroup)) &&
            (equipment == null || exercise.equipment == equipment),
      ),
    );
  }

