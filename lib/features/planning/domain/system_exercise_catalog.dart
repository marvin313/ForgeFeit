class _ExerciseSeed {
  const _ExerciseSeed(
    this.key,
    this.name,
    this.primaryMuscleGroup,
    this.equipment, {
    this.secondary = const [],
    this.aliases = const [],
    this.keywords = const [],
    this.trackingType = ExerciseTrackingType.weightAndRepetitions,
    this.bodyweightRelevant,
  });

  final String key;
  final String name;
  final MuscleGroup primaryMuscleGroup;
  final ExerciseEquipment equipment;
  final List<MuscleGroup> secondary;
  final List<String> aliases;
  final List<String> keywords;
  final ExerciseTrackingType trackingType;
  final bool? bodyweightRelevant;

  ExerciseSelection build() {
    final aliasValues = <String>{key.replaceAll('_', ' '), ...aliases};
    final keywordValues = <String>{
      primaryMuscleGroup.label,
      equipment.label,
      ...keywords,
    };
    final weightRelevant = switch (trackingType) {
      ExerciseTrackingType.weightAndRepetitions ||
      ExerciseTrackingType.weightAndDistance ||
      ExerciseTrackingType.weightAndDuration => true,
      _ => false,
    };
    final repetitionsRelevant = switch (trackingType) {
      ExerciseTrackingType.weightAndRepetitions ||
      ExerciseTrackingType.repetitions => true,
      _ => false,
    };
    final distanceRelevant = switch (trackingType) {
      ExerciseTrackingType.distanceAndDuration ||
      ExerciseTrackingType.weightAndDistance => true,
      _ => false,
    };
    final durationRelevant = switch (trackingType) {
      ExerciseTrackingType.duration ||
      ExerciseTrackingType.distanceAndDuration ||
      ExerciseTrackingType.weightAndDuration => true,
      _ => false,
    };

    return ExerciseSelection.system(
      key: key,
      name: name,
      primaryMuscleGroup: primaryMuscleGroup,
      secondaryMuscleGroups: List.unmodifiable(secondary),
      equipment: equipment,
      aliases: List.unmodifiable(aliasValues),
      keywords: List.unmodifiable(keywordValues),
      trackingType: trackingType,
      weightRelevant: weightRelevant,
      repetitionsRelevant: repetitionsRelevant,
      distanceRelevant: distanceRelevant,
      durationRelevant: durationRelevant,
      bodyweightRelevant:
          bodyweightRelevant ?? equipment == ExerciseEquipment.bodyweight,
    );
  }
}
